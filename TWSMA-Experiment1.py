# STEP 2: CREATE SENTIMENT DATASET

import pandas as pd

data = {
    "Review": [
        "This movie was absolutely amazing and enjoyable.",
        "Leonardo DiCaprio gave an excellent performance in this film.",
        "I loved the story and the acting was excellent.",
        "I watched this movie in Mumbai and really enjoyed it.",
        "The film was fantastic and the performances were brilliant.",
        "Tom Hanks was wonderful and made the movie very entertaining.",
        "The movie was boring and very disappointing.",
        "I hated the film because the story was terrible.",
        "The acting was poor and the movie was too long.",
        "This was a horrible and disappointing experience.",
        "The movie was dull and completely uninteresting.",
        "Netflix released this disappointing movie last year.",
        "The story was good and the characters were interesting.",
        "The movie had great visuals but the story was weak.",
        "Overall, I really enjoyed this entertaining movie."
    ],

    "Sentiment": [
        "Positive",
        "Positive",
        "Positive",
        "Positive",
        "Positive",
        "Positive",
        "Negative",
        "Negative",
        "Negative",
        "Negative",
        "Negative",
        "Negative",
        "Positive",
        "Negative",
        "Positive"
    ]
}

df = pd.DataFrame(data)

print("Sentiment Dataset:")
display(df)

# STEP 3: WORD-LEVEL TOKENIZATION

import nltk
from nltk.tokenize import word_tokenize

# Download tokenizer data
nltk.download('punkt')
nltk.download('punkt_tab')

# Apply word-level tokenization
df["Tokens"] = df["Review"].apply(word_tokenize)

print("Tokenized Reviews:")
display(df[["Review", "Tokens"]])

# STEP 4: STOP-WORD REMOVAL

from nltk.corpus import stopwords

# Download English stop words
nltk.download('stopwords')

# Get standard English stop words
stop_words = set(stopwords.words('english'))

# Remove stop words
df["Filtered_Tokens"] = df["Tokens"].apply(
    lambda tokens: [
        word for word in tokens
        if word.lower() not in stop_words
    ]
)

print("Reviews After Stop-Word Removal:")
display(df[["Review", "Tokens", "Filtered_Tokens"]])

# STEP 5: STEMMING USING PORTER STEMMER

from nltk.stem import PorterStemmer

# Create Porter Stemmer
stemmer = PorterStemmer()

# Apply stemming to filtered tokens
df["Stemmed_Tokens"] = df["Filtered_Tokens"].apply(
    lambda tokens: [
        stemmer.stem(word)
        for word in tokens
    ]
)

print("Reviews After Stemming:")
display(df[["Review", "Filtered_Tokens", "Stemmed_Tokens"]])

# STEP 6: LEMMATIZATION USING WORDNET LEMMATIZER

from nltk.stem import WordNetLemmatizer

# Download WordNet data
nltk.download('wordnet')
nltk.download('omw-1.4')

# Create WordNet Lemmatizer
lemmatizer = WordNetLemmatizer()

# Apply lemmatization to filtered tokens
df["Lemmatized_Tokens"] = df["Filtered_Tokens"].apply(
    lambda tokens: [
        lemmatizer.lemmatize(word)
        for word in tokens
    ]
)

print("Reviews After Lemmatization:")
display(df[["Review", "Filtered_Tokens", "Lemmatized_Tokens"]])

# STEP 7: COMPARISON OF STEMMING AND LEMMATIZATION

comparison = []

for original, stemmed, lemmatized in zip(
    df["Filtered_Tokens"],
    df["Stemmed_Tokens"],
    df["Lemmatized_Tokens"]
):
    for orig, stem, lemma in zip(original, stemmed, lemmatized):
        comparison.append((orig, stem, lemma))

comparison_df = pd.DataFrame(
    comparison,
    columns=["Original Word", "Stemmed Word", "Lemmatized Word"]
)

print("Stemming vs Lemmatization:")
display(comparison_df)

# STEP 8A: INSTALL AND LOAD SPACY ENGLISH MODEL


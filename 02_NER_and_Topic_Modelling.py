# STEP 13: ASSIGN DOMINANT TOPIC TO EACH ARTICLE

def get_dominant_topic(bow):

    topic_distribution = lda_model.get_document_topics(
        bow,
        minimum_probability=0
    )

    dominant_topic = max(
        topic_distribution,
        key=lambda x: x[1]
    )

    return dominant_topic[0], dominant_topic[1]

dominant_topics = []

for bow in corpus:

    topic_id, probability = get_dominant_topic(bow)

    dominant_topics.append(topic_id)

df["Dominant_Topic"] = [
    topic + 1
    for topic in dominant_topics
]

df["Topic_Probability"] = [
    get_dominant_topic(bow)[1]
    for bow in corpus
]


# STEP 4: NAMED ENTITY RECOGNITION USING SPACY

import spacy

# Load English spaCy model
nlp = spacy.load("en_core_web_sm")

# Function to extract selected entities
def extract_entities(text):
    doc = nlp(text)

    entities = []

    for ent in doc.ents:
        if ent.label_ in ["PERSON", "ORG", "GPE", "DATE"]:
            entities.append({
                "Entity": ent.text,
                "Label": ent.label_
            })

    return entities

# Apply NER
